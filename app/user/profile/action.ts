
"use server"

import { createClient } from "@/lib/supabase/server"

type AvatarResult = {
  success: boolean
  error?: string
}

export async function saveProfileAvatarAction(
  avatarPath: string
): Promise<AvatarResult> {
  const supabase = await createClient()

  const {
    data: { user },
    error: authError,
  } = await supabase.auth.getUser()

  if (authError || !user) {
    return {
      success: false,
      error: "Please log in to update your profile.",
    }
  }

  // Only accept image paths inside the current user's folder.
  const prefix = `${user.id}/`

  if (!avatarPath.startsWith(prefix)) {
    return {
      success: false,
      error: "Invalid profile image path.",
    }
  }

  const filename = avatarPath.slice(prefix.length)

  // Only allow filenames generated by our uploader.
  if (
    !/^avatar-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(jpg|png|webp)$/i.test(
      filename
    )
  ) {
    return {
      success: false,
      error: "Invalid profile image filename.",
    }
  }

  const { data, error } = await supabase
    .from("profiles")
    .update({
      avatar_path: avatarPath,
    })
    .eq("id", user.id)
    .select("id")
    .maybeSingle()

  if (error) {
    console.error("Profile avatar update failed:", error.message)

    return {
      success: false,
      error: "Unable to save your profile picture.",
    }
  }

  if (!data) {
    return {
      success: false,
      error: "Your profile record could not be found.",
    }
  }

  return { success: true }
}
